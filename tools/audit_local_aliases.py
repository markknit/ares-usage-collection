#!/usr/bin/env python3
"""Inventory every literal production-alias occurrence, including PDF references and supplied APKs."""
import argparse
import hashlib
import importlib.util
from pathlib import Path
import subprocess
from pypdf import PdfReader

ROOT = Path(__file__).resolve().parents[1]


def audit(apks):
    token = "ares" + ".local"
    result = ["# Local alias inventory", "", "Generated by `tools/audit_local_aliases.py`; includes tracked source and reviewable untracked files.",
              "Generated Android build caches are excluded from source rows; supplied APKs are inspected separately.", "",
              "Production defaults, historic evidence and documentation examples remain intentional.",
              "Builder-rendered payloads/Markdown and test PDFs replace production examples before sealing test packages.",
              "No historical acceptance record is rewritten to imply a test-profile result.", "",
              "| File | Line or PDF page | Occurrences |", "|---|---|---|"]
    files = subprocess.check_output(["git", "ls-files", "-co", "--exclude-standard"], cwd=ROOT, text=True).splitlines()
    for name in sorted(set(files)):
        if name.endswith("LOCAL_ALIAS_AUDIT.md"):
            continue
        path = ROOT / name
        if not path.is_file():
            continue
        if path.suffix == ".pdf":
            for index, page in enumerate(PdfReader(path).pages, 1):
                count = (page.extract_text() or "").count(token)
                if count:
                    result.append(f"| `{name}` | page {index} | {count} |")
            continue
        try:
            value = path.read_text(encoding="utf-8")
        except (UnicodeError, OSError):
            continue
        for number, line in enumerate(value.splitlines(), 1):
            if token in line:
                result.append(f"| `{name}` | {number} | {line.count(token)} |")
    result += ["", "## Compiled APK verification", ""]
    spec = importlib.util.spec_from_file_location("render_profile", ROOT / "offline-installer/tools/render_profile.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    for item in apks:
        profile, name = item.split("=", 1)
        path = Path(name)
        module.verify_apk(path, profile)
        result += [f"- {profile}: compiled collection/probe endpoints and literal cleartext policy PASS.",
                   f"  Debug APK SHA-256: `{hashlib.sha256(path.read_bytes()).hexdigest()}`."]
    return "\n".join(result) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apk", action="append", default=[])
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(audit(args.apk), encoding="utf-8")
